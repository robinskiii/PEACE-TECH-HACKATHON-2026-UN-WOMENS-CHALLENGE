-- ---------------------------------------------------------------------
-- Word database (lexicon)
-- ---------------------------------------------------------------------
create table lexicon (
  id             bigint generated by default as identity primary key,
  term           text not null,
  variants       text[] not null default '{}',
  language       text not null,                  -- tl, ceb, ilo, en
  country        text not null default 'PH',
  meaning        text,
  category       text not null default 'unclassified' references categories (code),
  severity       text not null default 'medium' check (severity in ('low', 'medium', 'high')),
  context_note   text,
  status         text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  raw_submission text,
  submitted_by   text,
  approved_by    text,
  ai_drafted     boolean not null default false,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index lexicon_status on lexicon (status, country, language);

-- Every change to the word list is logged, so a removed or edited word
-- can always be traced and restored
create table lexicon_audit (
  id         bigint generated always as identity primary key,
  lexicon_id bigint not null,
  action     text not null,
  old_row    jsonb,
  new_row    jsonb,
  changed_at timestamptz not null default now()
);

create or replace function public.lexicon_log_change()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into lexicon_audit (lexicon_id, action, old_row, new_row)
  values (coalesce(new.id, old.id), lower(tg_op),
          case when tg_op <> 'INSERT' then to_jsonb(old) end,
          case when tg_op <> 'DELETE' then to_jsonb(new) end);
  return null;
end $$;

create trigger lexicon_audit_log
  after insert or update or delete on lexicon
  for each row execute function public.lexicon_log_change();


