-- ---------------------------------------------------------------------
-- Reports sent by the extension ("Save as evidence")
-- ---------------------------------------------------------------------
create table reports (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  url               text,
  platform          text,
  lexicon_id        bigint references lexicon (id) on delete set null,
  matched_text      text,
  context_text      text,
  category          text not null default 'unclassified' references categories (code),
  reporter_role     text,
  country           text not null default 'PH',
  leader_id         bigint references leaders (id) on delete set null,
  screenshot_file   text,
  screenshot_sha256 text check (screenshot_sha256 is null or screenshot_sha256 ~ '^[0-9a-f]{64}$')
);
create index reports_leader_time on reports (leader_id, created_at);
create index reports_time on reports (created_at);

-- A saved screenshot and its fingerprint can never be changed afterwards
create or replace function public.reports_lock_evidence()
returns trigger language plpgsql
as $$
begin
  if old.screenshot_sha256 is not null
     and (new.screenshot_sha256 is distinct from old.screenshot_sha256
          or new.screenshot_file is distinct from old.screenshot_file) then
    raise exception 'Evidence is locked: the screenshot and its fingerprint cannot be changed';
  end if;
  return new;
end $$;

create trigger reports_lock_evidence
  before update on reports
  for each row execute function public.reports_lock_evidence();


